#!/usr/bin/env python3

import math
from pathlib import Path


MODEL_CONTEXT_LENGTH = 2048
MODEL_HEAD_DIMENSION = 96
ROPE_BASE = 10000.0
Q15_SCALE = 32768.0

ROPE_LUT_CONTEXT = MODEL_CONTEXT_LENGTH
ROPE_LUT_PAIRS = MODEL_HEAD_DIMENSION // 2


def q15(value: float) -> int:
    scaled = int(round(value * Q15_SCALE))
    if scaled > 32767:
        return 32767
    if scaled < -32768:
        return -32768
    return scaled


def format_array(name: str, values: list[int]) -> str:
    lines = [f"static const int16_t {name}[ROPE_LUT_CONTEXT * ROPE_LUT_PAIRS] = {{"]
    row_width = 8
    for idx in range(0, len(values), row_width):
        chunk = values[idx : idx + row_width]
        rendered = ", ".join(f"{value:6d}" for value in chunk)
        suffix = "," if (idx + row_width) < len(values) else ""
        lines.append(f"    {rendered}{suffix}")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    cos_values: list[int] = []
    sin_values: list[int] = []

    for pair_idx in range(ROPE_LUT_PAIRS):
        theta = ROPE_BASE ** (-(2.0 * pair_idx) / MODEL_HEAD_DIMENSION)
        for pos in range(ROPE_LUT_CONTEXT):
            angle = pos * theta
            cos_values.append(q15(math.cos(angle)))
            sin_values.append(q15(math.sin(angle)))

    out_path = Path(__file__).resolve().parent.parent / "rope_lut_full_q15.hpp"
    out_path.write_text(
        "\n".join(
            [
                "#pragma once",
                "#include <cstdint>",
                "",
                "// Generated by HLS-Verilog/test_data/gen_rope_lut.py",
                "// Full-model RoPE sin/cos lookup tables in Q1.15.",
                f"constexpr int ROPE_LUT_CONTEXT = {ROPE_LUT_CONTEXT};",
                f"constexpr int ROPE_LUT_PAIRS   = {ROPE_LUT_PAIRS};",
                "",
                format_array("ROPE_COS_Q15", cos_values),
                "",
                format_array("ROPE_SIN_Q15", sin_values),
                "",
            ]
        )
        + "\n"
    )


if __name__ == "__main__":
    main()
